package com.jtjmpm;

public class ControllerRotation {
    public float x;
    public float y;
    public float z;
    public float scalar;

    public ControllerRotation(float x, float y, float z, float scalar) {
        this.x = x;
        this.y = y;
        this.z = z;
        this.scalar = scalar;
    }
}
